const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{
  const browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_PATH});
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.goto('http://127.0.0.1:4173',{waitUntil:'networkidle'});
    assert.equal(await page.locator('select').count(),0,'No native dropdowns');
    assert.equal(await page.locator('terviora-choice').count(),9,'Search and alerts use custom choices');
    assert(await page.evaluate(()=>{const ids=[...document.querySelectorAll('[id]')].map(el=>el.id);return ids.length===new Set(ids).size;}),'Unique runtime IDs');
    const field=page.locator('#location'),button=field.getByRole('combobox');
    await button.focus();
    await page.keyboard.press('Enter');
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Escape');
    assert.equal(await field.evaluate(el=>el.value),'','Escape cancels tentative choice');
    assert.equal(await button.getAttribute('aria-expanded'),'false');
    await page.keyboard.press('Enter');
    await page.keyboard.press('End');
    await page.keyboard.press('Enter');
    assert.equal(await field.evaluate(el=>el.value),'Thrissur');
    assert.equal(await button.innerText(),'Thrissur');
    await page.keyboard.press('k');
    await page.keyboard.press('o');
    await page.keyboard.press('c');
    await page.keyboard.press('Enter');
    assert.equal(await field.evaluate(el=>el.value),'Kochi','Typeahead selection');
    await button.click();
    const search = field.getByRole('searchbox',{name:'Search cities'});
    await search.fill('puram');
    assert.equal(await field.getByRole('option').count(),1);
    assert(await field.getByRole('option',{name:'Thiruvananthapuram',exact:true}).isVisible());
    await search.fill('no matching city');
    assert.equal(await field.getByRole('option').count(),0);
    assert(await field.getByText('No cities match.').isVisible());
    await search.press('Enter');
    assert.equal(await field.evaluate(el=>el.value),'Kochi','No matches cannot change the selection');
    await search.press('Escape');
    await button.click();
    await page.keyboard.press('ArrowDown');
    await page.keyboard.press('Tab');
    assert.equal(await button.getAttribute('aria-expanded'),'false');
    assert.equal(await field.evaluate(el=>el.value),'Kochi','Tab dismisses without accidental selection');
    await button.click();
    await page.locator('#hero-title').click();
    assert.equal(await button.getAttribute('aria-expanded'),'false','Outside click dismisses');
    for(const [width,height,label] of [[1440,1000,'desktop'],[390,844,'mobile'],[320,812,'narrow']]){
      await page.setViewportSize({width,height});
      await button.click();
      const bounds=await field.getByRole('listbox').boundingBox();
      assert(bounds.x>=0&&bounds.y>=0&&bounds.x+bounds.width<=width&&bounds.y+bounds.height<=height,`${label} menu remains in viewport`);
      assert.equal(await field.getByRole('option',{name:'Kochi',exact:true}).getAttribute('aria-selected'),'true');
      const active=await search.getAttribute('aria-activedescendant');
      assert(active&&await page.locator(`#${active}`).count()===1,'Active option exists');
      await page.screenshot({path:`qa/screenshots/${label}-dropdown.png`});
      await field.getByRole('option',{name:'Thiruvananthapuram',exact:true}).click();
      assert.equal(await button.getAttribute('aria-expanded'),'false','Pointer selection closes menu');
      assert.equal(await field.evaluate(el=>el.value),'Thiruvananthapuram');
      await button.click();
      await field.getByRole('option',{name:'Kochi',exact:true}).click();
    }
    await page.locator('#property-search button[type=reset]').click();
    assert.equal(await field.evaluate(el=>el.value),'','Form reset restores value');
    assert.equal(await button.innerText(),'Anywhere','Form reset restores caption');
    await page.locator('#tab-commercial').click();
    await page.locator('#property-type').getByRole('combobox').click();
    assert.match(await page.locator('#property-type').getByRole('listbox').innerText(),/Office/);
    await page.keyboard.press('Escape');
    await page.locator('#quick-area').getByRole('combobox').click();
    await page.locator('#quick-area').getByRole('option',{name:'3,000+ sq ft',exact:true}).click();
    assert.equal(await page.locator('#min-area').inputValue(),'3000');
    await page.locator('#filter-toggle').click();
    await page.locator('#min-area').fill('2000');
    assert.equal(await page.locator('#quick-area').getByRole('combobox').innerText(),'2,000+ sq ft');
    await page.locator('#alert-email').fill('test@example.com');
    await page.locator('#alerts-form button[type=submit]').click();
    assert.equal(await page.locator('#alert-location').getByRole('combobox').getAttribute('aria-invalid'),'true','Required choice validates');
    assert.equal(await page.locator('#alert-message').isVisible(),false,'No success for missing choice');
    await page.locator('#alert-location').getByRole('option',{name:'Kochi',exact:true}).click();
    assert.equal(await page.locator('#alert-location').getByRole('combobox').getAttribute('aria-invalid'),null);
    await page.locator('#alerts-form button[type=submit]').click();
    assert.match(await page.locator('#alert-message').innerText(),/not been sent or stored/);
    assert.deepEqual(errors,[]);
    console.log('Passed: custom choices, keyboard navigation, typeahead, Escape/Tab/outside dismissal, touch selection, viewport placement, form reset, dynamic options, area sync, required validation, unique IDs, no browser errors.');
  }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
